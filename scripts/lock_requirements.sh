#!/usr/bin/env sh
# Re-pin requirements.lock after changing requirements*.txt (needs uv). Resolves for Windows + Linux on Python 3.12,
# constrained to the versions installed in the current venv. torch: CPU build on Linux (from the PyTorch CPU index,
# which only the Docker build adds), the PyPI build elsewhere. Usage: sh scripts/lock_requirements.sh [python]
set -eu
PY="${1:-python}"
TV=$("$PY" -c "import importlib.metadata as m; print(m.version('torch').split('+')[0])")
"$PY" -m pip freeze | grep -v '^torch==' > .lock-constraints.txt
printf 'torch==%s+cpu ; sys_platform == "linux"\n' "$TV" >> .lock-constraints.txt
uv pip compile requirements.txt --universal --python-version 3.12 -c .lock-constraints.txt --index-url https://pypi.org/simple \
  --extra-index-url https://download.pytorch.org/whl/cpu --index-strategy unsafe-best-match --no-header --no-annotate -q -o .lock-body.txt
{
  echo "# Pinned, cross-platform (Windows + Linux, Python 3.12) lock of requirements.txt, generated by scripts/lock_requirements.sh"
  echo "# from the development venv's versions. Linux needs the CPU torch index:"
  echo "#   pip install --extra-index-url https://download.pytorch.org/whl/cpu -r requirements.lock   (Docker does this)"
  grep -v '^torch==' .lock-body.txt
  printf "torch==%s+cpu ; sys_platform == 'linux'\ntorch==%s ; sys_platform != 'linux'\n" "$TV" "$TV"
} > requirements.lock
rm -f .lock-constraints.txt .lock-body.txt
echo "requirements.lock: $(grep -c '==' requirements.lock) pins"
